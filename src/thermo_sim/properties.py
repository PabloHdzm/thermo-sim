"""Result container for a stream: every thermodynamic and transport property.

Naming convention for energy properties
---------------------------------------
    <X>_<kind>_<scope>[_<phase>]        X in {H, S, Cp} (molar) or {h, s, cp} (mass)
    kind  : ig (ideal gas) | dep (departure) | total (= ig + dep)
    scope : mix (mixture)  | indiv (pure component)
    phase : gas | liq      -> per-phase value (NaN when the phase is absent)
            (no suffix)    -> active phase, or the molar/mass-weighted value in two-phase
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np


@dataclass(slots=True)
class StreamProperties:
    """All results of a Stream. See the module docstring for the naming convention."""
    # per-component flows
    molar_flows: np.ndarray = field(default_factory=lambda: np.array([]))
    mass_flows: np.ndarray = field(default_factory=lambda: np.array([]))
    # equilibrium
    sat_status: dict = field(default_factory=dict)
    phase: str = field(default='')   # 'vapor' | 'liquid' | 'two_phase'
    T: float = field(default=np.nan)
    TBubble: float = field(default=np.nan)
    TDew: float = field(default=np.nan)
    V_frac: float = field(default=np.nan)
    L_frac: float = field(default=np.nan)
    xi: np.ndarray = field(default_factory=lambda: np.array([]))
    yi: np.ndarray = field(default_factory=lambda: np.array([]))
    Ki: np.ndarray = field(default_factory=lambda: np.array([]))
    V: float = field(default=0.0)
    L: float = field(default=0.0)
    fn_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    fn_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    fm_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    fm_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    V_m: float = field(default=0.0)
    L_m: float = field(default=0.0)
    V_frac_m: np.ndarray = field(default_factory=lambda: np.array([]))
    L_frac_m: np.ndarray = field(default_factory=lambda: np.array([]))
    V_frac_m_total: float = field(default=0.0)
    L_frac_m_total: float = field(default=0.0)
    # density
    Z_liq_rho: float = field(default=np.nan)
    Vm_gas: float = field(default=np.nan)
    Vm_liq: float = field(default=np.nan)
    Vm_gas_eos: float = field(default=np.nan)
    Vm_liq_eos: float = field(default=np.nan)
    dens_mix_gas: float = field(default=np.nan)
    dens_mix_liq: float = field(default=np.nan)
    dens_pure_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    dens_pure_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    dens_pure: np.ndarray = field(default_factory=lambda: np.array([]))
    dens_mix: float = field(default=np.nan)
    dens_mol_mix_gas: float = field(default=np.nan)
    dens_mol_mix_liq: float = field(default=np.nan)
    dens_mol_mix: float = field(default=np.nan)
    dens_mol_pure_gas: float = field(default_factory=lambda: np.array([]))
    dens_mol_pure_liq: float = field(default_factory=lambda: np.array([]))
    dens_mol_pure: float = field(default_factory=lambda: np.array([]))
    fv: float = field(default=np.nan)
    visc_g: np.ndarray = field(default_factory=lambda: np.array([]))
    visc_l: np.ndarray = field(default_factory=lambda: np.array([]))
    visc_mix: float = field(default=np.nan)
    k_g: np.ndarray = field(default_factory=lambda: np.array([]))
    k_l: np.ndarray = field(default_factory=lambda: np.array([]))
    k_mix: float = field(default=np.nan)
    ind_sf: np.ndarray = field(default_factory=lambda: np.array([]))
    sf_mix: float = field(default=np.nan)
    # fugacity (array in the present phase, nan in the absent one)
    phi_v: object = field(default=np.nan)
    phi_l: object = field(default=np.nan)
    phi_pure: object = field(default=np.nan)
    phi_pure_v: object = field(default=np.nan)
    phi_pure_l: object = field(default=np.nan)
    phi: np.ndarray = field(default_factory=lambda: np.array([]))
    phi_mix: np.ndarray = field(default_factory=lambda: np.array([]))
    Ki_detail: dict = field(default_factory=dict, repr=False)
    Z_gas_eos: float = field(default=np.nan)
    Z_liq_eos: float = field(default=np.nan)
    Z_gas: float = field(default=np.nan)
    Z_liq: float = field(default=np.nan)
    Z_mix: float = field(default=np.nan)
    Vc:   np.ndarray = field(default_factory=lambda: np.array([]))   # m3/mol
    Zc:   np.ndarray = field(default_factory=lambda: np.array([]))
    Zra:  np.ndarray = field(default_factory=lambda: np.array([]))
    zra_source: np.ndarray = field(default_factory=lambda: np.array([], dtype=object))
    liquid_volume_model: str = field(default='')
    liquid_volume_source: str = field(default='') 
    MM_g: float = field(default=np.nan)
    MM_l: float = field(default=np.nan)
    # ideal-gas Cp of pure components
    Cp_liq_dippr: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_liq_dippr: np.ndarray = field(default_factory=lambda: np.array([]))
    # per-component ideal-gas aliases (same array, explicit name)
    Cp_ig_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    Cp_ig_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_ig_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_ig_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    # Cp departure, per component (EOS loop)
    Cp_dep_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    Cp_dep_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_dep_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_dep_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    # Cp total, per component
    Cp_total_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    Cp_total_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_total_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_total_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    # Cp, mixture
    Cp_ig_mix_gas: float = field(default=np.nan)
    Cp_ig_mix_liq: float = field(default=np.nan)
    Cp_dep_mix_gas: float = field(default=np.nan)
    Cp_dep_mix_liq: float = field(default=np.nan)
    Cp_total_mix_gas: float = field(default=np.nan)
    Cp_total_mix_liq: float = field(default=np.nan)
    cp_ig_mix_gas: float = field(default=np.nan)
    cp_ig_mix_liq: float = field(default=np.nan)
    cp_dep_mix_gas: float = field(default=np.nan)
    cp_dep_mix_liq: float = field(default=np.nan)
    cp_total_mix_gas: float = field(default=np.nan)
    cp_total_mix_liq: float = field(default=np.nan)

    # Cp aliases for the active phase (no suffix)
    Cp_ig_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    Cp_dep_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    Cp_total_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_ig_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_dep_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    cp_total_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    Cp_ig_mix: float = field(default=np.nan)
    Cp_dep_mix: float = field(default=np.nan)
    Cp_total_mix: float = field(default=np.nan)
    cp_ig_mix: float = field(default=np.nan)
    cp_dep_mix: float = field(default=np.nan)
    cp_total_mix: float = field(default=np.nan)

    # H
    HVAP: np.ndarray = field(default_factory=lambda: np.array([]))
    H_ig_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    H_ig_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    h_ig_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    h_ig_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    H_dep_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    H_dep_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    h_dep_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    h_dep_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    H_total_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    H_total_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    h_total_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    h_total_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    H_ig_mix_gas: float = field(default=np.nan)
    H_ig_mix_liq: float = field(default=np.nan)
    H_dep_mix_gas: float = field(default=np.nan)
    H_dep_mix_liq: float = field(default=np.nan)
    H_total_mix_gas: float = field(default=np.nan)
    H_total_mix_liq: float = field(default=np.nan)
    h_ig_mix_gas: float = field(default=np.nan)
    h_ig_mix_liq: float = field(default=np.nan)
    h_dep_mix_gas: float = field(default=np.nan)
    h_dep_mix_liq: float = field(default=np.nan)
    h_total_mix_gas: float = field(default=np.nan)
    h_total_mix_liq: float = field(default=np.nan)

    # aliases for the active phase
    H_ig_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    H_dep_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    H_total_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    h_ig_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    h_dep_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    h_total_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    H_ig_mix: float = field(default=np.nan)
    H_dep_mix: float = field(default=np.nan)
    H_total_mix: float = field(default=np.nan)
    h_ig_mix: float = field(default=np.nan)
    h_dep_mix: float = field(default=np.nan)
    h_total_mix: float = field(default=np.nan)

    # S
    S_ig_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    S_ig_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    s_ig_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    s_ig_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    S_dep_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    S_dep_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    s_dep_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    s_dep_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    S_total_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    S_total_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))
    s_total_indiv_gas: np.ndarray = field(default_factory=lambda: np.array([]))
    s_total_indiv_liq: np.ndarray = field(default_factory=lambda: np.array([]))

    S_ig_mix_gas: float = field(default=np.nan)
    S_ig_mix_liq: float = field(default=np.nan)
    S_dep_mix_gas: float = field(default=np.nan)
    S_dep_mix_liq: float = field(default=np.nan)
    S_total_mix_gas: float = field(default=np.nan)
    S_total_mix_liq: float = field(default=np.nan)
    s_ig_mix_gas: float = field(default=np.nan)
    s_ig_mix_liq: float = field(default=np.nan)
    s_dep_mix_gas: float = field(default=np.nan)
    s_dep_mix_liq: float = field(default=np.nan)
    s_total_mix_gas: float = field(default=np.nan)
    s_total_mix_liq: float = field(default=np.nan)

    # aliases for the active phase
    S_ig_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    S_dep_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    S_total_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    s_ig_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    s_dep_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    s_total_indiv: np.ndarray = field(default_factory=lambda: np.array([]))
    S_ig_mix: float = field(default=np.nan)
    S_dep_mix: float = field(default=np.nan)
    S_total_mix: float = field(default=np.nan)
    s_ig_mix: float = field(default=np.nan)
    s_dep_mix: float = field(default=np.nan)
    s_total_mix: float = field(default=np.nan)
    
    def __repr__(self) -> str:
        return (f"StreamProperties(phase='{self.phase}', "
                f"T={self.T:.2f} K, V_frac={self.V_frac:.3f})")
